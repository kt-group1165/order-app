// "第Ｎ条（…）" 行を条タイトル、続く行を本文として分解する。
// contract_articles_1_6 / contract_articles_8_20 の描画用。
export function parseContractArticles(text: string): { title: string; body: string }[] {
  const articles: { title: string; body: string }[] = [];
  for (const line of text.split("\n")) {
    if (/^第[0-9０-９]+条/.test(line)) {
      articles.push({ title: line, body: "" });
    } else if (articles.length > 0) {
      const cur = articles[articles.length - 1];
      cur.body = cur.body ? cur.body + "\n" + line : line;
    }
  }
  return articles;
}
