-- ============================================================
-- payroll_employees.phone_duty_pay
-- 電話当番の単価 (職員ごと)
-- ============================================================
-- 背景 (2026-07-29 user 確定):
--   電話当番の単価が職員によって異なる (村上 3,000円 / 安川・三枝 1,500円)。
--   将来的には揃える方針だが、当面は職員ごとの単価で計算する。
--
--   土日祝対応 (1件 6,000円 / 2件以上 10,000円) は全員共通のためコード側の定数のまま。
--   併給しないルールも不変 (土日祝対応がある日は電話当番を加算しない)。
-- ============================================================

BEGIN;

ALTER TABLE payroll_employees
  ADD COLUMN IF NOT EXISTS phone_duty_pay INT NOT NULL DEFAULT 3000
    CHECK (phone_duty_pay >= 0);

COMMENT ON COLUMN payroll_employees.phone_duty_pay IS
  '電話当番 1 回あたりの手当 (円)。統括営業本部の出勤簿で使用。既定 3,000';

COMMIT;
